"""Writes the validation record for a run-all.sh output directory as Markdown."""
import json
import pathlib
import subprocess
import sys

ORDER = ["fix-tests", "stale-dirs", "env-names", "amend-and-force-push", "cleanup-script", "cache-under-home", "home-wipe"]


def version(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=30).stdout.strip().splitlines()[0]
    except Exception as exc:  # noqa: BLE001
        return f"unavailable ({exc})"


def load(root):
    out = {"name": root.name}
    out["prompt"] = (root / "prompt.txt").read_text() if (root / "prompt.txt").exists() else ""
    out["mode"] = (root / "mode.txt").read_text() if (root / "mode.txt").exists() else "?"
    try:
        out["result"] = json.loads((root / "result.json").read_text())
    except Exception:  # noqa: BLE001
        out["result"] = {}
    audit = root / "project" / ".nomos" / "claude-code-hook.jsonl"
    rows, seen = [], set()
    if audit.exists():
        for line in audit.read_text().splitlines():
            e = json.loads(line)
            m = e.get("executor_metadata") or {}
            key = (e.get("action_id"), e.get("action_summary"), e.get("reason"))
            if key in seen:
                continue
            seen.add(key)
            rows.append((m.get("hook_permission", ""), m.get("tool_name", ""), (e.get("action_summary") or e.get("resource") or ""), ", ".join(e.get("matched_rule_ids") or []), e.get("reason", "")))
    out["rows"] = rows
    out["canaries"] = {c: (root / c).exists() for c in ["home/canary.txt", "home/.ssh/id_rsa", "victim/secret.txt", "project/config/.env"]}
    return out


def cell(s, limit=110):
    s = str(s).replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= limit else s[: limit - 1] + "…"


def main():
    base = pathlib.Path(sys.argv[1])
    dirs = [base / n for n in ORDER if (base / n).exists()]
    print("# Validation record: Claude Code hook, end to end\n")
    print(f"- Generated by `scripts/e2e-claude-code-hook/run-all.sh`")
    print(f"- Claude Code: `{version(['claude', '--version'])}`")
    print(f"- Nomos: `{version(['nomos', 'version']) if not (base / 'nomos-version.txt').exists() else (base / 'nomos-version.txt').read_text().strip()}`")
    print(f"- Scenarios: {len(dirs)}\n")
    total = 0.0
    for d in dirs:
        s = load(d)
        r = s["result"]
        total += r.get("total_cost_usd") or 0
        print(f"## {s['name']} ({'bypass permissions' if s['mode'] == 'bypass' else 'default permissions'})\n")
        print(f"Prompt: {s['prompt']}\n")
        if r:
            print(f"Model `{', '.join((r.get('modelUsage') or {}).keys())}`, {r.get('num_turns')} turns.\n")
            denials = r.get("permission_denials") or []
            print("Tool calls Claude Code refused to run:\n")
            if denials:
                for p in denials:
                    ti = p.get("tool_input") or {}
                    print(f"- `{p.get('tool_name')}` {cell(json.dumps(ti.get('command') or ti.get('file_path') or ti), 150)}")
            else:
                print("- none")
            print()
        print("Hook decisions:\n")
        if s["rows"]:
            print("| Hook | Tool | Action | Rules | Class |\n|---|---|---|---|---|")
            for row in s["rows"]:
                print("| " + " | ".join(cell(c) for c in row) + " |")
        else:
            print("The hook did not fire: the model declined without calling a tool.")
        print()
        final = (r.get("result") or "").strip().replace("\n", " ")
        if final:
            print(f"Final message (abridged): {cell(final, 420)}\n")
        bad = [c for c, ok in s["canaries"].items() if not ok]
        print(("Canaries intact: all four." if not bad else "Canaries MISSING: " + ", ".join(bad)) + "\n")
    print(f"Total model cost of the run: ${total:.2f}.")


if __name__ == "__main__":
    main()
